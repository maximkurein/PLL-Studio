export function LearnView() {
  const block = useStore((s) => s.block);
  const go = useStore((s) => s.go);
  const setFields = useStore((s) => s.setFields);
  const toast = useStore((s) => s.toast);
  const initial = (block && BLOCKS[block]?.learn) || "intro";
  const [id, setId] = useState(ARTICLES.some((a) => a.id === initial) ? initial : "intro");
  const art = ARTICLES.find((a) => a.id === id)!;
  const set = (f: Record<string, number>) => {
    void setFields(f).then(() => toast("info", `Записано: ${Object.entries(f).map(([k, v]) => `${k}=${v}`).join(", ")}`));
  };

  return (
    <div className="max-w-[1300px]">
      <PageHeader icon={<GraduationCap size={20} />} title="Академия PLL" subtitle="Короткие статьи о каждой технологии 8V97051 — с кнопками, которые сразу меняют конфигурацию, чтобы увидеть эффект." />
      <div className="grid gap-4 lg:grid-cols-[280px_minmax(0,1fr)]">
        <Card bodyClass="!p-2">
          <div className="flex flex-col">
            {ARTICLES.map((a, i) => (
              <button
                key={a.id}
                onClick={() => setId(a.id)}
                className={cx("text-left rounded-lg px-3 py-2 transition-colors", a.id === id ? "bg-accent/12 text-fg" : "text-fg2 hover:bg-panel3")}
              >
                <div className="text-[10.5px] text-muted num">Урок {i + 1}</div>
                <div className="text-[12.5px] font-medium leading-snug">{a.title}</div>
              </button>
            ))}
          </div>
        </Card>
        <Card>
          <article className="prose-ru max-w-[760px]">
            <h2 className="text-[19px] font-semibold tracking-tight mb-1">{art.title}</h2>
            <p className="!text-fg !text-[13.5px]">{art.lead}</p>
            {art.body}
          </article>
          <div className="mt-4 rounded-xl border border-accent/25 bg-accent/6 p-3">
            <div className="flex items-center gap-2 text-[12px] font-semibold text-accent mb-2">
              <FlaskConical size={14} /> Попробуйте сами
            </div>
            <div className="flex flex-wrap gap-2">
              {art.tries(go, set).map((t) => (
                <Button key={t.label} size="sm" onClick={t.run}>
                  {t.label}
                </Button>
              ))}
            </div>
          </div>
        </Card>
      </div>
    </div>
  );
}
